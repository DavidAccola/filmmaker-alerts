void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Check for single instance lock
  final canRun = await SingleInstanceManager.acquireLock();
  if (!canRun) {
    debugPrint('[Main] Another instance is already running. Exiting.');
    exit(1);
  }

  // Configure image cache to prevent unbounded memory growth
  imageCache.maximumSize = 100; // Maximum number of images to cache
  imageCache.maximumSizeBytes = 50 * 1024 * 1024; // 50MB maximum cache size

  // Reduce GC pressure by being more aggressive with memory cleanup
  // This helps prevent the 4-second freeze after idle
  imageCache.clear();
  imageCache.clearLiveImages();

  // 0. Initialize window manager (Windows only)
  if (Platform.isWindows) {
    debugPrint('[Main] Initializing window manager for Windows');
    await windowManager.ensureInitialized();
    debugPrint('[Main] Window manager initialized');
    
    WindowOptions windowOptions = const WindowOptions(
      size: Size(1280, 720),
      minimumSize: Size(400, 500),
      center: true,
      backgroundColor: Colors.transparent,
      skipTaskbar: false,
      titleBarStyle: TitleBarStyle.normal,
    );
    
    debugPrint('[Main] Setting up window ready callback');
    windowManager.waitUntilReadyToShow(windowOptions, () async {
      debugPrint('[Main] Window ready callback - showing and focusing window');
      await windowManager.show();
      await windowManager.focus();
      
      // Set prevent close to true from the start
      debugPrint('[Main] Setting preventClose to true');
      await windowManager.setPreventClose(true);
      debugPrint('[Main] Window shown, focused, and preventClose set');
    });
  } else {
    debugPrint('[Main] Skipping window manager - not Windows platform');
  }

  // 1. Load Environment Variables
  await dotenv.load(fileName: ".env");

  // 2. Initialize Hive
  if (Platform.isWindows) {
    final appSupportDir = await getApplicationSupportDirectory();
    await Hive.initFlutter(appSupportDir.path);
  } else {
    await Hive.initFlutter();
  }

  // 3. Register Adapters (Generated by build_runner)
  Hive.registerAdapter(ContributorAdapter());
  Hive.registerAdapter(ContributorTypeAdapter());
  Hive.registerAdapter(TvNotificationPreferencesAdapter());
  Hive.registerAdapter(LatestWorkAdapter());
  Hive.registerAdapter(PreferencesAdapter());
  Hive.registerAdapter(NotificationHistoryEntryAdapter());
  Hive.registerAdapter(NotificationReasonAdapter());
  Hive.registerAdapter(NotificationEventAdapter());
  Hive.registerAdapter(MovieCacheEntryAdapter());
  Hive.registerAdapter(TvShowCacheEntryAdapter());
  Hive.registerAdapter(TvEpisodeCacheEntryAdapter());
  
  // Register new contributor details adapters
  Hive.registerAdapter(WorkTypeAdapter());
  Hive.registerAdapter(ReleaseTypeAdapter());
  Hive.registerAdapter(StreamingTypeAdapter());
  Hive.registerAdapter(ContributorRoleAdapter());
  Hive.registerAdapter(StreamingOptionAdapter());
  Hive.registerAdapter(WorkAdapter());
  Hive.registerAdapter(ContributorDetailAdapter());
  Hive.registerAdapter(CastMemberAdapter());
  Hive.registerAdapter(CrewMemberAdapter());
  Hive.registerAdapter(MovieDetailAdapter());
  Hive.registerAdapter(TvShowDetailAdapter());
  Hive.registerAdapter(TvSeasonAdapter());
  Hive.registerAdapter(TvEpisodeDetailAdapter());
  Hive.registerAdapter(TvSeasonDetailAdapter());
  Hive.registerAdapter(SeasonEpisodeAdapter());

  // Register watchlist adapters
  Hive.registerAdapter(WatchlistEntryAdapter());
  Hive.registerAdapter(ContributorSnapshotAdapter());
  Hive.registerAdapter(ReleaseNotificationPreferencesAdapter());
  Hive.registerAdapter(StatusRecordAdapter());
  Hive.registerAdapter(WatchStatusAdapter());
  Hive.registerAdapter(EpisodeStatusEntryAdapter());
  Hive.registerAdapter(SeasonStatusEntryAdapter());
  Hive.registerAdapter(MovieStatusEntryAdapter());
  Hive.registerAdapter(CollectionOrderAdapter());

  // 4. Open Boxes with error handling for lock conflicts
  try {
    await _openHiveBoxes();
  } catch (e) {
    debugPrint('[Main] ERROR: Failed to open Hive boxes: $e');
    // Continue anyway - the app will show an error dialog when it tries to access data
    // This allows the UI to load and display a helpful error message
  }

  // 5. Initialize Riverpod Container
  final container = ProviderContainer();

  // 6. Initialize TV Cache Repository
  final tvCacheRepo = container.read(tvCacheRepositoryProvider);
  await tvCacheRepo.init();

  // 7. Initialize Notification Service with callback for navigation
  final notificationService = container.read(notificationServiceProvider);
  await notificationService.init(
    onAction: (payload) {
      if (payload == 'app://history') {
        // Navigate to history tab
        container.read(selectedTabProvider.notifier).setTab(1); // History tab index
      }
    },
  );

  // 8. Initialize System Tray (Windows only)
  if (Platform.isWindows) {
    debugPrint('[Main] Initializing system tray service for Windows');
    final systemTrayService = container.read(systemTrayServiceProvider);
    systemTrayService.setContainer(container); // Pass the container for release checking
    await systemTrayService.init();
    debugPrint('[Main] System tray service initialization completed');
  } else {
    debugPrint('[Main] Skipping system tray - not Windows platform');
  }

  if (!kIsWeb && (Platform.isAndroid || Platform.isIOS)) {
    await Workmanager().initialize(
      callbackDispatcher,
      // Note: isInDebugMode is deprecated but we keep it for backward compatibility
      // The parameter has no effect in newer versions
    );
    
    // Get user's scheduled notification time from preferences
    final prefsBox = Hive.box<Preferences>(AppConstants.preferencesBox);
    final prefs = prefsBox.isEmpty ? Preferences() : prefsBox.getAt(0)!;
    
    // Parse schedule time (format: "HH:MM")
    int scheduleHour = 9;
    int scheduleMinute = 0;
    try {
      final parts = prefs.scheduleTime.split(':');
      if (parts.length == 2) {
        scheduleHour = int.parse(parts[0]);
        scheduleMinute = int.parse(parts[1]);
      }
    } catch (e) {
      debugPrint('[Main] Error parsing scheduleTime "${prefs.scheduleTime}": $e, using default 9:00');
    }
    
    // Calculate initial delay for the scheduled time
    final now = DateTime.now();
    var firstRun = DateTime(now.year, now.month, now.day, scheduleHour, scheduleMinute);
    if (firstRun.isBefore(now)) {
      firstRun = firstRun.add(const Duration(days: 1));
    }
    final initialDelay = firstRun.difference(now);

    debugPrint('[Main] Scheduling background task for ${scheduleHour.toString().padLeft(2, '0')}:${scheduleMinute.toString().padLeft(2, '0')} daily');
    debugPrint('[Main] First run scheduled in ${initialDelay.inMinutes} minutes');

    await Workmanager().registerPeriodicTask(
      "daily-check-task",
      taskName,
      frequency: const Duration(hours: 24),
      initialDelay: initialDelay,
      constraints: Constraints(
        networkType: NetworkType.connected,
      ),
    );
  } else {
    debugPrint('[Main] Workmanager not supported on this platform. Background tasks skipped.');
  }

  // Read initial animation preference (won't change until restart)
  final prefsRepo = container.read(preferencesRepositoryProvider);
  final initialReduceAnimations = prefsRepo.getPreferences().reduceAnimations ?? false;

  runApp(
    UncontrolledProviderScope(
      container: container,
      child: MyApp(reduceAnimations: initialReduceAnimations),
    ),
  );
}

/// Opens all Hive boxes with retry logic for lock conflicts
Future<void> _openHiveBoxes() async {
  const maxRetries = 3;
  const retryDelay = Duration(milliseconds: 500);
  
  final boxes = [
    (AppConstants.contributorsBox, Contributor),
    (AppConstants.preferencesBox, Preferences),
    (AppConstants.historyBox, NotificationHistoryEntry),
    (AppConstants.movieCacheBox, MovieCacheEntry),
    (AppConstants.contributorDetailsBox, ContributorDetail),
    (AppConstants.movieDetailsBox, MovieDetail),
    (AppConstants.tvDetailsBox, TvShowDetail),
    (AppConstants.tvEpisodeDetailsBox, TvEpisodeDetail),
    (AppConstants.tvSeasonDetailsBox, TvSeasonDetail),
    (AppConstants.watchlistEntriesBox, WatchlistEntry),
    (AppConstants.episodeStatusesBox, EpisodeStatusEntry),
    (AppConstants.seasonStatusesBox, SeasonStatusEntry),
    (AppConstants.movieStatusesBox, MovieStatusEntry),
    (AppConstants.collectionOrdersBox, CollectionOrder),
  ];

  for (final (boxName, _) in boxes) {
    int retryCount = 0;
    while (retryCount < maxRetries) {
      try {
        debugPrint('[Main] Opening Hive box: $boxName (attempt ${retryCount + 1}/$maxRetries)');
        
        // Use dynamic typing to open boxes without needing specific type info
        if (boxName == AppConstants.contributorsBox) {
          await Hive.openBox<Contributor>(boxName);
        } else if (boxName == AppConstants.preferencesBox) {
          await Hive.openBox<Preferences>(boxName);
        } else if (boxName == AppConstants.historyBox) {
          await Hive.openBox<NotificationHistoryEntry>(boxName);
        } else if (boxName == AppConstants.movieCacheBox) {
          await Hive.openBox<MovieCacheEntry>(boxName);
        } else if (boxName == AppConstants.contributorDetailsBox) {
          await Hive.openBox<ContributorDetail>(boxName);
        } else if (boxName == AppConstants.movieDetailsBox) {
          await Hive.openBox<MovieDetail>(boxName);
        } else if (boxName == AppConstants.tvDetailsBox) {
          await Hive.openBox<TvShowDetail>(boxName);
        } else if (boxName == AppConstants.tvEpisodeDetailsBox) {
          await Hive.openBox<TvEpisodeDetail>(boxName);
        } else if (boxName == AppConstants.tvSeasonDetailsBox) {
          await Hive.openBox<TvSeasonDetail>(boxName);
        } else if (boxName == AppConstants.watchlistEntriesBox) {
          await Hive.openBox<WatchlistEntry>(boxName);
        } else if (boxName == AppConstants.episodeStatusesBox) {
          await Hive.openBox<EpisodeStatusEntry>(boxName);
        } else if (boxName == AppConstants.seasonStatusesBox) {
          await Hive.openBox<SeasonStatusEntry>(boxName);
        } else if (boxName == AppConstants.movieStatusesBox) {
          await Hive.openBox<MovieStatusEntry>(boxName);
        } else if (boxName == AppConstants.collectionOrdersBox) {
          await Hive.openBox<CollectionOrder>(boxName);
        }
        
        debugPrint('[Main] Successfully opened Hive box: $boxName');
        break; // Success, move to next box
      } catch (e) {
        retryCount++;
        if (retryCount >= maxRetries) {
          debugPrint('[Main] FAILED to open Hive box after $maxRetries attempts: $boxName - $e');
          rethrow; // Give up after max retries
        }
        debugPrint('[Main] Retry $retryCount/$maxRetries for box $boxName after delay...');
        await Future.delayed(retryDelay);
      }
    }
  }
}

